/// Converts the app's Simplified Chinese copy to Traditional Chinese.
///
/// The app keeps Simplified Chinese as the source language. Phrase replacements
/// handle the few context-sensitive UI terms first; the character table then
/// covers the common characters used by the remaining copy. Keeping this local
/// avoids a runtime/network dependency and also lets state-layer feedback use
/// the same conversion as widgets.
String toTraditionalChinese(String source) {
  var result = source;
  for (final entry in _traditionalPhrases.entries) {
    result = result.replaceAll(entry.key, entry.value);
  }
  return String.fromCharCodes(
    result.runes.map((rune) => _traditionalCharacters[rune] ?? rune),
  );
}

